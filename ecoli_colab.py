# ЯЧЕЙКА 8. Итоговая программа: картинка -> E. coli / Not E. coli / Uncertain + интерфейс
@torch.no_grad()
def predict_image(img, bundle=None):
    bundle = bundle or BUNDLE
    img = img.convert("RGB")
    if min(img.size) < 96:
        return {"prediction": "Uncertain", "confidence": None, "status": "Uncertain",
                "message": "Изображение слишком маленькое (меньше 96 px по короткой стороне)."}
    x = eval_tfm(img.resize((IMG_SIZE, IMG_SIZE), Image.BILINEAR)).unsqueeze(0).to(DEVICE)
    bundle["model"].eval()
    p = float(softmax_T(bundle["model"](x).cpu().numpy(), bundle["T"])[0, 1])
    conf = max(p, 1 - p)
    if conf < bundle["tau"]:
        return {"prediction": "Uncertain", "confidence": conf, "status": "Uncertain",
                "message": (f"Модель не уверена (уверенность {conf:.0%} ниже порога {bundle['tau']:.0%}). "
                            "Возможно, изображение отличается от обучающих (увеличение, окраска, фон) - нужна проверка человеком.")}
    return {"prediction": "E. coli" if p >= 0.5 else "Not E. coli", "confidence": conf, "status": "Result",
            "message": "Исследовательский прототип, не диагностический инструмент."}


