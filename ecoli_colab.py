_k = np.arange(32)[:, None]
_i = np.arange(32)[None, :]
DCT32 = np.cos(np.pi * (2 * _i + 1) * _k / 64)


def phash_bits(img, hash_size=8):
    g = img.convert("L").resize((32, 32), Image.LANCZOS)
    a = np.asarray(g, dtype=np.float64)
    low = (DCT32 @ a @ DCT32.T)[:hash_size, :hash_size].flatten()
    return (low > np.median(low[1:])).astype(np.uint8)


def hamming_matrix(a, b=None):
    a = a.astype(np.int32)
    b = a if b is None else b.astype(np.int32)
    return a @ (1 - b).T + (1 - a) @ b.T


def group_duplicates(bits, thresh):
    n = len(bits)
    parent = list(range(n))

    def find(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    dist = hamming_matrix(bits)
    ii, jj = np.where(np.triu(dist <= thresh, k=1))
    for i, j in zip(ii, jj):
        ri, rj = find(i), find(j)
        if ri != rj:
            parent[ri] = rj
    return np.array([find(i) for i in range(n)])


def color_stats(img):
    rgb = np.asarray(img, dtype=np.float32)
    gray = rgb.mean(axis=2)
    lap = (4 * gray[1:-1, 1:-1] - gray[:-2, 1:-1] - gray[2:, 1:-1]
           - gray[1:-1, :-2] - gray[1:-1, 2:])
    b = max(1, gray.shape[0] // 10)
    border = np.concatenate([gray[:b].ravel(), gray[-b:].ravel(), gray[:, :b].ravel(), gray[:, -b:].ravel()])
    return {"mean_r": float(rgb[..., 0].mean()), "mean_g": float(rgb[..., 1].mean()),
            "mean_b": float(rgb[..., 2].mean()), "brightness": float(gray.mean()),
            "contrast": float(gray.std()), "sharpness": float(lap.var()),
            "border_brightness": float(border.mean())}


